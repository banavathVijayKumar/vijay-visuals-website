export function getDemoById(id: VideoDemo['id']): VideoDemo {
  return VIDEO_DEMOS.find((demo) => demo.id === id) ?? VIDEO_DEMOS[0];
}

export function getSubtitlePath(demo: VideoDemo, lang: Lang): string {
  return `${demo.subtitleBasePath}.${lang}.vtt`;
}

export interface SubtitleTrack {
  src: string;
  srcLang: Lang;
  label: string;
  fellBackToEnglish: boolean;
}

/** Unlisted/unsupported language codes fall back to English; missing asset files are not detected. */
export function getSubtitleTrack(demo: VideoDemo, lang: Lang): SubtitleTrack {
  const available = VIDEO_LANGUAGES.some((item) => item.code === lang);
  const effectiveLang: Lang = available ? lang : 'en';
  const meta = VIDEO_LANGUAGES.find((item) => item.code === effectiveLang);
  return {
    src: getSubtitlePath(demo, effectiveLang),
    srcLang: effectiveLang,
    label: meta?.englishName || effectiveLang,
    fellBackToEnglish: !available,
  };
}

